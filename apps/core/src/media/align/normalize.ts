/**
 * CJK 归一化：NFKC + casefold → 繁→简映射表逐字替换 → 标点归一（全半角/中英文标点统一，
 * 全部折成空格供 token 切分；DEC §6B.4：ASR 中文标点不可靠，匹配层干脆全剥）。
 */
export function normalizeCjk(text: string): string {
  // JS 无 casefold（那是 Python），等价物是 toLowerCase（对 CJK 无副作用）
  let out = text.normalize("NFKC").toLowerCase();
  let mapped = "";
  for (const ch of out) mapped += T2S_MAP[ch] ?? ch;
  out = mapped;
  // 标点（含 ASR 转出的英文逗号/句号、中文全角标点、省略号、引号等）统一折空格
  out = out.replace(/[，。！？；：、""''《》（）\[\]{}【】…—·,\.!?:;()"'"«»\-_~「」『』]/g, " ");
  // 连续空白折叠
  return out.replace(/\s+/g, " ").trim();
}

/**
 * 坑二：多字 token 按字数均分回单字时间戳。
 * `我的` 一个 token 0.1s → 两字各 0.05s（DEC §6B.3 实测样例）。
 * token 内非 CJK 长度按码点数计（逐 codepoint 切，标点字符已在 normalize 层处理）。
 */
export function spreadTokenTiming(
  token: string,
  startSec: number,
  endSec: number,
): CharTiming[] {
  const chars = Array.from(token);
  if (chars.length === 0) return [];
  const dur = (endSec - startSec) / chars.length;
  return chars.map((char, i) => ({
    char,
    startSec: startSec + i * dur,
    endSec: startSec + (i + 1) * dur,
  }));
}

/** 把 token 数组整体展开成逐字流（DEC §13.1 _word_unit_stream 的 TS 版）。 */
export function spreadTokens(tokens: { word: string; startSec: number; endSec: number }[]): {
  chars: CharTiming[];
  /** 每个字归属的 token 下标（容错匹配时定位回原 token 用） */
  owners: number[];
} {
  const chars: CharTiming[] = [];
  const owners: number[] = [];
  tokens.forEach((t, idx) => {
    // token 也要归一化：ASR 会把标点粘在字上（「深,」）、出繁体（「漸」）——
    // 归一化后按空格切成子 token 再拆字（标点被折空格即剥离）
    for (const seg of normalizeCjk(t.word).split(" ")) {
      if (seg === "") continue;
      // 子 token 的时刻区间按字符数比例从原 token 均分（近似：标点剥离后余字均摊原区间）
      for (const c of spreadTokenTiming(seg, t.startSec, t.endSec)) {
        chars.push(c);
        owners.push(idx);
      }
    }
  });
  return { chars, owners };
}
